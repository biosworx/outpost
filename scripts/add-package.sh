#!/usr/bin/env bash
#
# Add a package directory.
#
# Usage: scripts/add-package.sh [options] <name>
#
# By default the package is linked to its AUR original: packages/<l>/<name>/aur.conf
# pins the current AUR commit, and CI builds AUR's files from it.
#
# Options:
#   -o, --override         also copy AUR's files into override/ to edit
#   -s, --standalone       not on AUR: write an annotated template PKGBUILD
#   -a, --arch any|x86_64  template arch (with --standalone; default x86_64)
#   -h, --help             show this help
#
# Refuses to touch an existing directory.

set -euo pipefail
# shellcheck source=lib/common.sh
source "$(dirname "$0")/lib/common.sh"
# shellcheck source=lib/vercmp.sh
source "$(dirname "$0")/lib/vercmp.sh"
# shellcheck source=lib/aur.sh
source "$(dirname "$0")/lib/aur.sh"

usage() {
  sed -n '3,/^$/{s/^# \{0,1\}//;p}' "$0"
  exit "${1:-0}"
}

arch="x86_64" name="" standalone=0 override=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    -a|--arch)
      [[ $# -ge 2 ]] || die "--arch needs a value"
      arch="$2"
      shift
      ;;
    -s|--standalone) standalone=1 ;;
    -o|--override) override=1 ;;
    -h|--help) usage 0 ;;
    -*) warn "unknown option: $1"; usage 1 ;;
    *)
      [[ -z "$name" ]] || die "only one package name may be given"
      name="$1"
      ;;
  esac
  shift
done

[[ -n "$name" ]] || usage 1
case "$arch" in
  any|x86_64) ;;
  *) die "--arch must be 'any' or 'x86_64'" ;;
esac
[[ "$standalone" -eq 0 || "$override" -eq 0 ]] || die "--override needs an AUR package; drop --standalone"

# makepkg rules: lowercase alphanumerics and @._+-, not starting with - or .
if [[ ! "$name" =~ ^[a-z0-9@_+][a-z0-9@._+-]*$ ]]; then
  die "invalid package name '$name' (allowed: a-z 0-9 @ . _ + -, not starting with - or .)"
fi

target="$(pkg_dir "$name")"
[[ ! -e "$target" ]] || die "$(pkg_path "$name") already exists"

# --- AUR-linked ----------------------------------------------------------------------
if [[ "$standalone" -eq 0 ]]; then
  require_cmd curl jq git
  info="$(curl -fsS "${AUR_URL}/rpc/v5/info?arg[]=${name}")" || die "could not query the AUR"
  base="$(jq -r '.results[0].PackageBase // empty' <<<"$info")"
  [[ -n "$base" ]] || die "${name} is not on the AUR; use --standalone for a template PKGBUILD"
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' EXIT
  aur_clone "$base" "" "${work}/aur" || die "could not clone AUR ${base}"
  commit="$(git -C "${work}/aur" rev-parse HEAD)"

  mkdir -p "$target"
  {
    printf '# AUR original this package builds from. The pin moves through PRs\n'
    printf '# opened by the daily check (scripts/ci/propose-aur.sh).\n'
    [[ "$base" == "$name" ]] || printf 'pkgbase=%s\n' "$base"
    printf 'commit=%s\n' "$commit"
  } >"${target}/aur.conf"
  ok "linked $(pkg_path "$name") to AUR ${base} $(srcinfo_version "${work}/aur") (${commit:0:12})"
  [[ "$base" == "$name" ]] || warn "AUR ${base} is a split package: building from AUR makes all of its packages"

  next="Read AUR's PKGBUILD: CI builds and signs exactly that."
  if [[ "$override" -eq 1 ]]; then
    create_override "$name" "${work}/aur" "edited by hand."
    ok "copied AUR's files to $(pkg_path "$name")/override/"
    next="Edit $(pkg_path "$name")/override/. Bump pkgver or pkgrel past AUR's, or
     put permanent=1 in override/override.conf; otherwise AUR still wins."
  fi

  cat >&2 <<EOF

Next steps:
  1. ${next}
  2. Build in a clean chroot: scripts/local-build.sh ${name}
  3. Optional: add $(pkg_path "$name")/update.conf for automatic update PRs
     (copy packages/l/legcord/update.conf). Upstream releases AUR lacks then
     arrive as override PRs.
  4. Commit and push; CI builds, signs and publishes it to [${REPO_NAME}].
EOF
  exit 0
fi

# --- Standalone ------------------------------------------------------------------------
maintainer_name="$(git -C "$REPO_ROOT" config user.name 2>/dev/null || true)"
maintainer_email="$(git -C "$REPO_ROOT" config user.email 2>/dev/null || true)"
maintainer="${maintainer_name:-Your Name} <${maintainer_email:-you@example.com}>"

mkdir -p "$target"

# Quoted heredoc: nothing below is expanded; the @...@ placeholders are
# substituted afterwards with sed.
cat >"${target}/PKGBUILD" <<'PKGBUILD'
# Maintainer: @MAINTAINER@
# Contributor: Claude <noreply@anthropic.com>
#
# Template generated by scripts/add-package.sh. Delete comments you don't need.
# Reference: https://wiki.archlinux.org/title/PKGBUILD
#            https://wiki.archlinux.org/title/Arch_package_guidelines

# Package name; must match the directory name under packages/<l>/.
pkgname=@PKGNAME@

# Upstream version. Bump pkgrel (not pkgver) to republish the same version:
# CI skips versions that are already in the [aurstrich] database.
pkgver=0.1.0
pkgrel=1

# Short (< 80 chars) description, no leading article or package name.
pkgdesc="TODO: describe @PKGNAME@"

# 'any' for scripts/data with no compiled code, 'x86_64' otherwise.
arch=('@ARCH@')

url="https://example.com/@PKGNAME@"

# SPDX license identifiers, e.g. 'MIT', 'GPL-3.0-or-later', 'Apache-2.0'.
license=('TODO')

# Runtime dependencies. Packages from [aurstrich] itself may be listed here, as
# long as they were published in an earlier push.
depends=()

# Needed only to build (compilers, build systems). base-devel is implied.
makedepends=()

# Needed only to run check().
checkdepends=()

# Optional runtime extras, as 'pkg: why it is useful'.
optdepends=()

# Other names this package satisfies / replaces / cannot coexist with.
provides=()
conflicts=()
replaces=()

# Files under /etc that pacman should not overwrite on upgrade.
backup=()

# Sources: URLs or files committed next to this PKGBUILD. Use a
# "name::url" prefix to rename downloads.
source=("${pkgname}-${pkgver}.tar.gz::https://example.com/releases/v${pkgver}.tar.gz")

# Run `updpkgsums` after editing source=() to fill these in. Never commit
# 'SKIP' for release tarballs; only VCS sources (git+https://...) may skip.
sha256sums=('SKIP')

# Optional: runs after sources are extracted, before build().
prepare() {
  cd "${pkgname}-${pkgver}"
}

build() {
  cd "${pkgname}-${pkgver}"
  # ./configure --prefix=/usr
  # make
}

# Optional: test suite. Skipped with makepkg --nocheck.
check() {
  cd "${pkgname}-${pkgver}"
  # make check
}

package() {
  cd "${pkgname}-${pkgver}"
  # make DESTDIR="${pkgdir}" install
  # install -Dm644 LICENSE "${pkgdir}/usr/share/licenses/${pkgname}/LICENSE"
}
PKGBUILD

# '|' delimiter: the maintainer string contains '<', '>' and '@' but not '|'.
sed -i \
  -e "s|@MAINTAINER@|${maintainer//|/}|" \
  -e "s|@PKGNAME@|${name}|g" \
  -e "s|@ARCH@|${arch}|" \
  "${target}/PKGBUILD"

ok "created $(pkg_path "$name")/PKGBUILD"
cat >&2 <<EOF

Next steps:
  1. Edit $(pkg_path "$name")/PKGBUILD (search for TODO).
  2. Fill in checksums:       (cd $(pkg_path "$name") && updpkgsums)
  3. Build in a clean chroot: scripts/local-build.sh ${name}
  4. Optional: add $(pkg_path "$name")/update.conf for automatic update PRs
     (copy packages/l/legcord/update.conf).
  5. Commit and push; CI builds, signs and publishes it to [${REPO_NAME}].
EOF
