#!/usr/bin/env bash
#
# Scaffold a new package directory with an annotated template PKGBUILD.
#
# Usage: scripts/add-package.sh [--arch any|x86_64] <name>
#
# Creates packages/<name>/PKGBUILD. Refuses to touch an existing directory.

set -euo pipefail
# shellcheck source=lib/common.sh
source "$(dirname "$0")/lib/common.sh"

usage() {
  sed -n '3,/^$/{s/^# \{0,1\}//;p}' "$0"
  exit "${1:-0}"
}

arch="x86_64" name=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    -a|--arch)
      [[ $# -ge 2 ]] || die "--arch needs a value"
      arch="$2"
      shift
      ;;
    -h|--help) usage 0 ;;
    -*) warn "unknown option: $1"; usage 1 ;;
    *)
      [[ -z "$name" ]] || die "only one package name may be given"
      name="$1"
      ;;
  esac
  shift
done

[[ -n "$name" ]] || usage 1
case "$arch" in
  any|x86_64) ;;
  *) die "--arch must be 'any' or 'x86_64'" ;;
esac

# makepkg rules: lowercase alphanumerics and @._+-, not starting with - or .
if [[ ! "$name" =~ ^[a-z0-9@_+][a-z0-9@._+-]*$ ]]; then
  die "invalid package name '$name' (allowed: a-z 0-9 @ . _ + -, not starting with - or .)"
fi

target="${PACKAGES_DIR}/${name}"
[[ ! -e "$target" ]] || die "packages/${name} already exists"

maintainer_name="$(git -C "$REPO_ROOT" config user.name 2>/dev/null || true)"
maintainer_email="$(git -C "$REPO_ROOT" config user.email 2>/dev/null || true)"
maintainer="${maintainer_name:-Your Name} <${maintainer_email:-you@example.com}>"

mkdir -p "$target"

# Quoted heredoc: nothing below is expanded; the @...@ placeholders are
# substituted afterwards with sed.
cat >"${target}/PKGBUILD" <<'PKGBUILD'
# Maintainer: @MAINTAINER@
# Contributor: Claude <noreply@anthropic.com>
#
# Template generated by scripts/add-package.sh. Delete comments you don't need.
# Reference: https://wiki.archlinux.org/title/PKGBUILD
#            https://wiki.archlinux.org/title/Arch_package_guidelines

# Package name; must match the directory name under packages/.
pkgname=@PKGNAME@

# Upstream version. Bump pkgrel (not pkgver) to republish the same version:
# CI skips versions that are already in the [aurstrich] database.
pkgver=0.1.0
pkgrel=1

# Short (< 80 chars) description, no leading article or package name.
pkgdesc="TODO: describe @PKGNAME@"

# 'any' for scripts/data with no compiled code, 'x86_64' otherwise.
arch=('@ARCH@')

url="https://example.com/@PKGNAME@"

# SPDX license identifiers, e.g. 'MIT', 'GPL-3.0-or-later', 'Apache-2.0'.
license=('TODO')

# Runtime dependencies. Packages from [aurstrich] itself may be listed here, as
# long as they were published in an earlier push.
depends=()

# Needed only to build (compilers, build systems). base-devel is implied.
makedepends=()

# Needed only to run check().
checkdepends=()

# Optional runtime extras, as 'pkg: why it is useful'.
optdepends=()

# Other names this package satisfies / replaces / cannot coexist with.
provides=()
conflicts=()
replaces=()

# Files under /etc that pacman should not overwrite on upgrade.
backup=()

# Sources: URLs or files committed next to this PKGBUILD. Use a
# "name::url" prefix to rename downloads.
source=("${pkgname}-${pkgver}.tar.gz::https://example.com/releases/v${pkgver}.tar.gz")

# Run `updpkgsums` after editing source=() to fill these in. Never commit
# 'SKIP' for release tarballs; only VCS sources (git+https://...) may skip.
sha256sums=('SKIP')

# Optional: runs after sources are extracted, before build().
prepare() {
  cd "${pkgname}-${pkgver}"
}

build() {
  cd "${pkgname}-${pkgver}"
  # ./configure --prefix=/usr
  # make
}

# Optional: test suite. Skipped with makepkg --nocheck.
check() {
  cd "${pkgname}-${pkgver}"
  # make check
}

package() {
  cd "${pkgname}-${pkgver}"
  # make DESTDIR="${pkgdir}" install
  # install -Dm644 LICENSE "${pkgdir}/usr/share/licenses/${pkgname}/LICENSE"
}
PKGBUILD

# '|' delimiter: the maintainer string contains '<', '>' and '@' but not '|'.
sed -i \
  -e "s|@MAINTAINER@|${maintainer//|/}|" \
  -e "s|@PKGNAME@|${name}|g" \
  -e "s|@ARCH@|${arch}|" \
  "${target}/PKGBUILD"

ok "created packages/${name}/PKGBUILD"
cat >&2 <<EOF

Next steps:
  1. Edit packages/${name}/PKGBUILD (search for TODO).
  2. Fill in checksums:       (cd packages/${name} && updpkgsums)
  3. Build in a clean chroot: scripts/local-build.sh ${name}
  4. Optional: add packages/${name}/update.conf for automatic update PRs
     (copy packages/legcord/update.conf).
  5. Commit and push; CI builds, signs and publishes it to [${REPO_NAME}].
EOF
