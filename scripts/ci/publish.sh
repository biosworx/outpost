#!/usr/bin/env bash
#
# Sync the [aurstrich] repository database with Backblaze B2.
#
# Usage:
#   publish.sh pull   Fetch the current aurstrich.{db,files}.tar.gz into $OUT_DIR
#                     so repo-add builds on the existing state. Run as root
#                     before building.
#   publish.sh push   Add packages listed in $OUT_DIR/.built to the database,
#                     then upload: package files first, database second.
#   publish.sh remove <name>
#                     Remove packages/<l>/<name> (all its split packages) from the
#                     database and upload it; prune then deletes its files.
#   publish.sh prune  Permanently delete package files the published database
#                     no longer references, then every old (hidden) version
#                     B2 keeps of anything under the prefix, superseded
#                     databases included. Run after the Cloudflare purge.
#
# Env: B2_BUCKET, RCLONE_CONFIG_B2_{TYPE,ACCOUNT,KEY}, GPGKEY, GNUPGHOME,
#      PRUNE (default 1; set 0 to keep superseded package files)
#
# Deletes are permanent: B2 would otherwise only hide a deleted file and
# keep its bytes, and keep every overwritten database as an old version.

set -euo pipefail
# shellcheck source=../lib/common.sh
source "$(dirname "$0")/../lib/common.sh"

require_cmd rclone bsdtar
require_env B2_BUCKET

# Uploads to B2 sometimes stall mid-transfer. rclone's default idle --timeout
# (5m) then turned a 30-55 MiB package upload into 6-13 minutes; at 60s a
# stalled transfer is retried after a minute instead. -v puts the transfer
# stats and retries in the log.
RCLONE_FLAGS=(-v --stats-one-line --stats 30s --retries 5 --low-level-retries 10
  --timeout 60s --contimeout 15s)
export RCLONE_CONFIG_B2_HARD_DELETE=true
REMOTE="$(remote_path)"

WORK_TMP="$(mktemp -d)"
trap 'rm -rf "$WORK_TMP"' EXIT

pull() {
  mkdir -p "$OUT_DIR"
  group_start "Pulling ${REPO_NAME} database from ${REMOTE}"
  # Only the real archives are needed; the plain-name copies and signatures
  # are regenerated by repo-add during push.
  # rclone exits 3 ("directory not found") when nothing has been published
  # under the prefix yet; that is the normal first-run state, not an error.
  local rc=0
  rclone copy "${RCLONE_FLAGS[@]}" --retries 1 --max-depth 1 \
    --include "/${DB_ARCHIVE}" --include "/${FILES_ARCHIVE}" \
    "$REMOTE" "$OUT_DIR" 2>"${WORK_TMP}/pull.err" || rc=$?
  case "$rc" in
    0) ;;
    3) log "${REMOTE} does not exist yet (first publish)" ;;
    *) cat "${WORK_TMP}/pull.err" >&2; die "failed to pull database (rclone exit $rc)" ;;
  esac

  if [[ -s "${OUT_DIR}/${DB_ARCHIVE}" ]]; then
    bsdtar -tf "${OUT_DIR}/${DB_ARCHIVE}" >/dev/null \
      || die "pulled ${DB_ARCHIVE} is not a valid archive; refusing to continue"
    ok "pulled ${DB_ARCHIVE} ($(db_filenames "${OUT_DIR}/${DB_ARCHIVE}" | wc -l) packages)"
  else
    warn "no existing database found; a new one will be created"
  fi
  group_end
}

push() {
  require_cmd repo-add gpg
  require_env GPGKEY

  local built_list="${OUT_DIR}/.built"
  if [[ ! -s "$built_list" ]]; then
    ok "no newly built packages; nothing to publish"
    return 0
  fi

  cd "$OUT_DIR"
  if [[ "$(id -u)" -eq 0 ]]; then
    chown -R "${BUILD_USER:-builder}:${BUILD_USER:-builder}" "$OUT_DIR"
  fi

  # --- Stage packages next to the database -------------------------------------
  local pkgs=() path file
  while IFS= read -r path; do
    [[ -n "$path" ]] || continue
    file="$(basename "$path")"
    if [[ "$path" != "${OUT_DIR}/${file}" ]]; then
      mv -f "$path" "$path.sig" "$OUT_DIR/"
    fi
    pkgs+=("$file")
  done <"$built_list"

  # --- Update and sign the database ------------------------------------------------
  group_start "Updating ${DB_ARCHIVE}"
  as_builder repo-add --sign --key "$GPGKEY" --verify --remove --prevent-downgrade \
    "$DB_ARCHIVE" "${pkgs[@]}"
  finalize_db
  group_end

  # --- Stage 1: package binaries -----------------------------------------------------
  group_start "Uploading packages"
  local pkg_list="${WORK_TMP}/packages.list"
  for file in "${pkgs[@]}"; do
    printf '%s\n%s.sig\n' "$file" "$file"
  done >"$pkg_list"
  # --immutable: never overwrite a published package with different bytes.
  rclone copy "${RCLONE_FLAGS[@]}" --immutable --files-from-raw "$pkg_list" \
    "$OUT_DIR" "$REMOTE"
  ok "uploaded ${#pkgs[@]} package(s)"
  group_end

  # --- Stage 2: database -----------------------------------------------------------------
  upload_db
}

# Remove every package built from packages/<l>/<name> (matched on %BASE%, so split
# packages go too) from the database and publish it. The package files stay
# until `publish.sh prune`, which must run after the Cloudflare purge.
# Sets the step output "changed" to true/false.
remove() {
  local name="${1:-}"
  [[ -n "$name" ]] || die "usage: $(basename "$0") remove <name>"
  require_cmd repo-remove gpg
  require_env GPGKEY
  [[ -s "${OUT_DIR}/${DB_ARCHIVE}" ]] || die "no database in ${OUT_DIR}; run 'publish.sh pull' first"

  cd "$OUT_DIR"
  if [[ "$(id -u)" -eq 0 ]]; then
    chown -R "${BUILD_USER:-builder}:${BUILD_USER:-builder}" "$OUT_DIR"
  fi

  local entries="${WORK_TMP}/entries.tsv" pkgnames=()
  db_entries "$DB_ARCHIVE" >"$entries"
  mapfile -t pkgnames < <(awk -F'\t' -v b="$name" '$1 == b { print $2 }' "$entries")
  if [[ "${#pkgnames[@]}" -eq 0 ]]; then
    warn "${name} is not in the ${REPO_NAME} database; nothing to remove"
    set_output changed false
    return 0
  fi

  # Warn (don't block) when other packages in the repo still depend on it.
  local dependents
  dependents="$(awk -F'\t' -v b="$name" -v names=" ${pkgnames[*]} " '
    $1 != b { n = split($3, deps, " "); for (i = 1; i <= n; i++) if (index(names, " " deps[i] " ")) print $2 }
  ' "$entries" | sort -u | paste -sd ' ')"
  [[ -z "$dependents" ]] || warn "still depended on by: ${dependents}"

  # Remember exactly which files this orphans, so prune can delete them even
  # when the database ends up empty (where it otherwise refuses to run).
  local before="${WORK_TMP}/before.list"
  db_filenames "$DB_ARCHIVE" | sort -u >"$before"

  group_start "Removing ${pkgnames[*]} from ${DB_ARCHIVE}"
  as_builder repo-remove --sign --key "$GPGKEY" "$DB_ARCHIVE" "${pkgnames[@]}"
  comm -23 "$before" <(db_filenames "$DB_ARCHIVE" | sort -u) >"${OUT_DIR}/.removed"
  finalize_db
  group_end

  upload_db
  set_output changed true
}

# B2 has no symlinks: replace repo-add/repo-remove's links with real copies so
# pacman's aurstrich.db / aurstrich.files requests resolve to actual objects,
# then check every object exists and the signatures verify. Run in $OUT_DIR.
finalize_db() {
  local base file
  for base in "${REPO_NAME}.db" "${REPO_NAME}.files"; do
    cp --remove-destination "${base}.tar.gz" "$base"
    cp --remove-destination "${base}.tar.gz.sig" "${base}.sig"
  done

  for file in "${DB_OBJECTS[@]}"; do
    [[ -f "$file" && ! -L "$file" ]] || die "expected regular file missing: $file"
  done
  for base in "${REPO_NAME}.db" "${REPO_NAME}.files"; do
    as_builder gpg --batch --quiet --verify "${base}.sig" "$base" 2>/dev/null \
      || die "signature verification failed for $base"
  done
  ok "database updated and verified"
}

upload_db() {
  group_start "Uploading database"
  local db_list="${WORK_TMP}/db.list"
  printf '%s\n' "${DB_OBJECTS[@]}" >"$db_list"
  rclone copy "${RCLONE_FLAGS[@]}" --ignore-times --files-from-raw "$db_list" \
    "$OUT_DIR" "$REMOTE"
  if [[ -f "${OUT_DIR}/${REPO_NAME}.asc" ]]; then
    rclone copyto "${RCLONE_FLAGS[@]}" "${OUT_DIR}/${REPO_NAME}.asc" \
      "$(remote_base)/${REPO_NAME}.asc"
  fi
  ok "database published"
  group_end
}

# Print "base<TAB>name<TAB>space-separated depend names" for each package in a
# repo database. Version constraints are stripped from depends.
db_entries() {
  { bsdtar -xOf "$1" '*/desc' 2>/dev/null || true; } | awk '
    function flush() { if (name != "") print (base != "" ? base : name) "\t" name "\t" deps }
    /^%FILENAME%$/ { flush(); name = ""; base = ""; deps = ""; section = ""; next }
    /^%[A-Z0-9]+%$/ { section = $0; next }
    /^$/ { section = ""; next }
    section == "%NAME%" { name = $0 }
    section == "%BASE%" { base = $0 }
    section == "%DEPENDS%" { sub(/[<>=].*/, ""); deps = deps (deps == "" ? "" : " ") $0 }
    END { flush() }
  '
}

# Remove package files from the bucket that the published database no longer
# references. Run after the CDN purge so edge-cached old databases have expired.
prune() {
  if [[ "${PRUNE:-1}" == "0" ]]; then
    log "PRUNE=0; keeping superseded package files"
    return 0
  fi
  [[ -s "${OUT_DIR}/${DB_ARCHIVE}" ]] || { log "no local database; nothing to prune"; return 0; }

  group_start "Pruning superseded packages"
  local keep="${WORK_TMP}/keep.list" remote_files="${WORK_TMP}/remote.list" stale="${WORK_TMP}/stale.list"

  db_filenames "${OUT_DIR}/${DB_ARCHIVE}" | while IFS= read -r file; do
    printf '%s\n%s.sig\n' "$file" "$file"
  done | sort -u >"$keep"

  if [[ -s "$keep" ]]; then
    rclone lsf "${RCLONE_FLAGS[@]}" --files-only --max-depth 1 \
      --include '*.pkg.tar.*' "$REMOTE" | sort -u >"$remote_files"
    comm -23 "$remote_files" "$keep" >"$stale"
  elif [[ -s "${OUT_DIR}/.removed" ]]; then
    # The last package was just removed: delete exactly its files.
    while IFS= read -r file; do
      printf '%s\n%s.sig\n' "$file" "$file"
    done <"${OUT_DIR}/.removed" >"$stale"
  else
    warn "database lists no packages; refusing to prune"
    group_end
    return 0
  fi

  if [[ -s "$stale" ]]; then
    log "removing $(wc -l <"$stale") stale file(s):"
    sed 's/^/    /' "$stale" >&2
    rclone delete "${RCLONE_FLAGS[@]}" --files-from-raw "$stale" "$REMOTE"
  else
    log "no stale package files"
  fi

  # Old versions: overwritten databases, and files an earlier run only hid.
  rclone cleanup "${RCLONE_FLAGS[@]}" "$REMOTE"
  ok "removed old file versions from ${REMOTE}"
  group_end
}

case "${1:-}" in
  pull) pull ;;
  push) push ;;
  remove) shift; remove "$@" ;;
  prune) prune ;;
  *) die "usage: $(basename "$0") pull|push|remove <name>|prune" ;;
esac
