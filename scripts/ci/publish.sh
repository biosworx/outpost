#!/usr/bin/env bash
#
# Sync the [aurstrich] repository database with Backblaze B2.
#
# Usage:
#   publish.sh pull   Fetch the current aurstrich.{db,files}.tar.gz into $OUT_DIR
#                     so repo-add builds on the existing state. Run as root
#                     before building.
#   publish.sh push   Add packages listed in $OUT_DIR/.built to the database,
#                     then upload: package files first, database second.
#   publish.sh prune  Delete package files the published database no longer
#                     references (run after the Cloudflare purge).
#
# Env: B2_BUCKET, RCLONE_CONFIG_B2_{TYPE,ACCOUNT,KEY}, GPGKEY, GNUPGHOME,
#      PRUNE (default 1; set 0 to keep superseded package files)

set -euo pipefail
# shellcheck source=../lib/common.sh
source "$(dirname "$0")/../lib/common.sh"

require_cmd rclone bsdtar
require_env B2_BUCKET

RCLONE_FLAGS=(--stats-one-line --stats 30s --retries 5 --low-level-retries 10)
REMOTE="$(remote_path)"

WORK_TMP="$(mktemp -d)"
trap 'rm -rf "$WORK_TMP"' EXIT

pull() {
  mkdir -p "$OUT_DIR"
  group_start "Pulling ${REPO_NAME} database from ${REMOTE}"
  # Only the real archives are needed; the plain-name copies and signatures
  # are regenerated by repo-add during push.
  # rclone exits 3 ("directory not found") when nothing has been published
  # under the prefix yet; that is the normal first-run state, not an error.
  local rc=0
  rclone copy "${RCLONE_FLAGS[@]}" --retries 1 --max-depth 1 \
    --include "/${DB_ARCHIVE}" --include "/${FILES_ARCHIVE}" \
    "$REMOTE" "$OUT_DIR" 2>"${WORK_TMP}/pull.err" || rc=$?
  case "$rc" in
    0) ;;
    3) log "${REMOTE} does not exist yet (first publish)" ;;
    *) cat "${WORK_TMP}/pull.err" >&2; die "failed to pull database (rclone exit $rc)" ;;
  esac

  if [[ -s "${OUT_DIR}/${DB_ARCHIVE}" ]]; then
    bsdtar -tf "${OUT_DIR}/${DB_ARCHIVE}" >/dev/null \
      || die "pulled ${DB_ARCHIVE} is not a valid archive; refusing to continue"
    ok "pulled ${DB_ARCHIVE} ($(db_filenames "${OUT_DIR}/${DB_ARCHIVE}" | wc -l) packages)"
  else
    warn "no existing database found; a new one will be created"
  fi
  group_end
}

push() {
  require_cmd repo-add gpg
  require_env GPGKEY

  local built_list="${OUT_DIR}/.built"
  if [[ ! -s "$built_list" ]]; then
    ok "no newly built packages; nothing to publish"
    return 0
  fi

  cd "$OUT_DIR"
  if [[ "$(id -u)" -eq 0 ]]; then
    chown -R "${BUILD_USER:-builder}:${BUILD_USER:-builder}" "$OUT_DIR"
  fi

  # --- Stage packages next to the database -------------------------------------
  local pkgs=() path file
  while IFS= read -r path; do
    [[ -n "$path" ]] || continue
    file="$(basename "$path")"
    if [[ "$path" != "${OUT_DIR}/${file}" ]]; then
      mv -f "$path" "$path.sig" "$OUT_DIR/"
    fi
    pkgs+=("$file")
  done <"$built_list"

  # --- Update and sign the database ------------------------------------------------
  group_start "Updating ${DB_ARCHIVE}"
  as_builder repo-add --sign --key "$GPGKEY" --verify --remove --prevent-downgrade \
    "$DB_ARCHIVE" "${pkgs[@]}"

  # B2 has no symlinks: replace repo-add's links with real copies so
  # pacman's aurstrich.db / aurstrich.files requests resolve to actual objects.
  local base
  for base in "${REPO_NAME}.db" "${REPO_NAME}.files"; do
    cp --remove-destination "${base}.tar.gz" "$base"
    cp --remove-destination "${base}.tar.gz.sig" "${base}.sig"
  done

  for file in "${DB_OBJECTS[@]}"; do
    [[ -f "$file" && ! -L "$file" ]] || die "expected regular file missing: $file"
  done
  for base in "${REPO_NAME}.db" "${REPO_NAME}.files"; do
    as_builder gpg --batch --quiet --verify "${base}.sig" "$base" 2>/dev/null \
      || die "signature verification failed for $base"
  done
  ok "database updated and verified"
  group_end

  # --- Stage 1: package binaries -----------------------------------------------------
  group_start "Uploading packages"
  local pkg_list="${WORK_TMP}/packages.list" db_list="${WORK_TMP}/db.list"
  for file in "${pkgs[@]}"; do
    printf '%s\n%s.sig\n' "$file" "$file"
  done >"$pkg_list"
  # --immutable: never overwrite a published package with different bytes.
  rclone copy "${RCLONE_FLAGS[@]}" --immutable --files-from-raw "$pkg_list" \
    "$OUT_DIR" "$REMOTE"
  ok "uploaded ${#pkgs[@]} package(s)"
  group_end

  # --- Stage 2: database -----------------------------------------------------------------
  group_start "Uploading database"
  printf '%s\n' "${DB_OBJECTS[@]}" >"$db_list"
  rclone copy "${RCLONE_FLAGS[@]}" --ignore-times --files-from-raw "$db_list" \
    "$OUT_DIR" "$REMOTE"
  if [[ -f "${OUT_DIR}/${REPO_NAME}.asc" ]]; then
    rclone copyto "${RCLONE_FLAGS[@]}" "${OUT_DIR}/${REPO_NAME}.asc" \
      "$(remote_base)/${REPO_NAME}.asc"
  fi
  ok "database published"
  group_end
}

# Remove package files from the bucket that the published database no longer
# references. Run after the CDN purge so edge-cached old databases have expired.
prune() {
  if [[ "${PRUNE:-1}" == "0" ]]; then
    log "PRUNE=0; keeping superseded package files"
    return 0
  fi
  [[ -s "${OUT_DIR}/${DB_ARCHIVE}" ]] || { log "no local database; nothing to prune"; return 0; }

  group_start "Pruning superseded packages"
  local keep="${WORK_TMP}/keep.list" remote_files="${WORK_TMP}/remote.list" stale="${WORK_TMP}/stale.list"

  db_filenames "${OUT_DIR}/${DB_ARCHIVE}" | while IFS= read -r file; do
    printf '%s\n%s.sig\n' "$file" "$file"
  done | sort -u >"$keep"

  if [[ ! -s "$keep" ]]; then
    warn "database lists no packages; refusing to prune"
    group_end
    return 0
  fi

  rclone lsf "${RCLONE_FLAGS[@]}" --files-only --max-depth 1 \
    --include '*.pkg.tar.*' "$REMOTE" | sort -u >"$remote_files"
  comm -23 "$remote_files" "$keep" >"$stale"

  if [[ -s "$stale" ]]; then
    log "removing $(wc -l <"$stale") stale file(s):"
    sed 's/^/    /' "$stale" >&2
    rclone delete "${RCLONE_FLAGS[@]}" --files-from-raw "$stale" "$REMOTE"
  else
    log "no stale package files"
  fi
  group_end
}

case "${1:-}" in
  pull) pull ;;
  push) push ;;
  prune) prune ;;
  *) die "usage: $(basename "$0") pull|push|prune" ;;
esac
